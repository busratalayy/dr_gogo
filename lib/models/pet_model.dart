class PetModel {


  final String name;
  final String type;
  final String breed;
  final int age;
  final double weight;
  final String gender;
  final String imagePath;



  PetModel({
    required this.name,
    required this.type,
    required this.breed,
    required this.age,
    required this.weight,
    required this.gender,
    required this.imagePath,
  });
}